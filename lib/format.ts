/**
 * 収集時に空白へ平坦化された議案要旨の改行を、箇条書きマーカーで復元する。
 * 元テキストの改行は収集時に半角スペースに潰れているため、
 * スペース直後のマーカー (一、/ １ / イ など) を段落・項目の先頭とみなす。
 */
export const formatSummary = (text: string): string =>
  text
    .replace(/ (?=[一二三四五六七八九十]+、)/g, "\n\n")
    .replace(/ (?=[０-９][０-９]? )/g, "\n")
    .replace(/ (?=[イロハニホヘトチリヌルヲ] )/g, "\n")
